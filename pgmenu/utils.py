def only_alpha_blending(source_alpha, dest_alpha):
    alpha = source_alpha / 255
    one_minus_alpha = 1 - alpha

    new_a = ((source_alpha * alpha) + (one_minus_alpha * dest_alpha))

    return new_a


# Bypasses division by 0 Error
def div(a, b, round_num=None):
    try:
        div_num = a / b
        if round_num is not None:
            div_num = round(div_num)

    except ZeroDivisionError:
        div_num = float('inf')

    return div_num
